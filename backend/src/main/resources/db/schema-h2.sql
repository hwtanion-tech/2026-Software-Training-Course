CREATE TABLE IF NOT EXISTS sys_user (
 id BIGINT AUTO_INCREMENT PRIMARY KEY,
 username VARCHAR(50) NOT NULL UNIQUE,
 password_hash VARCHAR(255) NOT NULL,
 display_name VARCHAR(50) NOT NULL,
 role VARCHAR(20) NOT NULL CHECK (role IN ('PUBLISHER','ADMIN')),
 enabled BOOLEAN NOT NULL DEFAULT TRUE,
 created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
 updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE TABLE IF NOT EXISTS news_category (
 id BIGINT AUTO_INCREMENT PRIMARY KEY,
 name VARCHAR(50) NOT NULL UNIQUE,
 sort_order INT NOT NULL DEFAULT 0,
 enabled BOOLEAN NOT NULL DEFAULT TRUE,
 created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE TABLE IF NOT EXISTS news (
 id BIGINT AUTO_INCREMENT PRIMARY KEY,
 category_id BIGINT NOT NULL REFERENCES news_category(id),
 title VARCHAR(200) NOT NULL CHECK (CHAR_LENGTH(TRIM(title)) > 0),
 summary VARCHAR(500) NOT NULL DEFAULT '',
 body MEDIUMTEXT NOT NULL CHECK (CHAR_LENGTH(TRIM(body)) > 0),
 author_name VARCHAR(50) NOT NULL,
 creator_id BIGINT NOT NULL REFERENCES sys_user(id),
 status VARCHAR(20) NOT NULL DEFAULT 'DRAFT' CHECK (status IN ('DRAFT','PUBLISHED','WITHDRAWN')),
 published_at TIMESTAMP,
 created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
 updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
 CHECK (status <> 'PUBLISHED' OR published_at IS NOT NULL)
);
CREATE TABLE IF NOT EXISTS notice (
 id BIGINT AUTO_INCREMENT PRIMARY KEY,
 title VARCHAR(200) NOT NULL CHECK (CHAR_LENGTH(TRIM(title)) > 0),
 body MEDIUMTEXT NOT NULL CHECK (CHAR_LENGTH(TRIM(body)) > 0),
 publisher_unit VARCHAR(100) NOT NULL,
 creator_id BIGINT NOT NULL REFERENCES sys_user(id),
 status VARCHAR(20) NOT NULL DEFAULT 'DRAFT' CHECK (status IN ('DRAFT','PUBLISHED','WITHDRAWN')),
 published_at TIMESTAMP,
 created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
 updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
 CHECK (status <> 'PUBLISHED' OR published_at IS NOT NULL)
);
CREATE INDEX IF NOT EXISTS idx_news_public ON news(status,published_at,id);
CREATE INDEX IF NOT EXISTS idx_news_category_public ON news(category_id,status,published_at,id);
CREATE INDEX IF NOT EXISTS idx_news_creator ON news(creator_id);
CREATE INDEX IF NOT EXISTS idx_notice_public ON notice(status,published_at,id);
CREATE INDEX IF NOT EXISTS idx_notice_creator ON notice(creator_id);
